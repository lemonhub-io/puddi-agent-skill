"""Regenerate the Puddi module that embeds the distributable skill."""

from pathlib import Path


root = Path(__file__).resolve().parents[1]
skill = (root / "skills/puddi/SKILL.md").read_text(encoding="utf-8")
escapes = str.maketrans({char: "\\" + char for char in '\\"{}'})
module = "// Generated by scripts/embed-skill.py from skills/puddi/SKILL.md.\n"
module += f'pub const SKILL_TEXT: Str = "{skill.translate(escapes)}"\n'
(root / "src/skill_text.pud").write_text(module, encoding="utf-8", newline="\n")
